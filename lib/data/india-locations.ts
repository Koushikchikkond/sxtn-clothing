/**
 * Returns sorted list of cities for a given state.
 * If the state is not recognized, returns an empty array.
 */
export function getCitiesForState(stateName: string): string[] {
  if (!stateName) return [];
  const foundKey = Object.keys(INDIAN_CITIES_BY_STATE).find(
    (k) => k.toLowerCase() === stateName.trim().toLowerCase()
  );
  return foundKey ? INDIAN_CITIES_BY_STATE[foundKey] : [];
}

